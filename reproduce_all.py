def main():
    parser = argparse.ArgumentParser(
        description="Reproduce all paper tables end-to-end")
    parser.add_argument("--table", default="all",
                        choices=["all","1","2","3","4","5","6","e13","e13b",
                                 "e13c","e13d","e14","verify"],
                        help="Which table to reproduce (default: all)")
    parser.add_argument("--skip-preprocess", action="store_true",
                        help="Skip PVDAQ preprocessing step")
    parser.add_argument("--force-preprocess", action="store_true",
                        help="Force re-run of PVDAQ preprocessing")
    args = parser.parse_args()

    print("=" * 70)
    print("  REPRODUCE ALL — JST Paper Results Verification")
    print("=" * 70)

    data_ok = check_data()
    if not data_ok:
        print("\n[ERROR] Missing data files. Cannot proceed.")
        sys.exit(1)

    if not args.skip_preprocess:
        preprocess_pvdaq(force=args.force_preprocess)

    results = {}
    if args.table in ("all", "1"):
        results["Table1"] = run_table1()
    if args.table in ("all", "2"):
        results["Table2"] = run_table2()
    if args.table in ("all", "3"):
        results["Table3"] = run_table3()
    if args.table in ("all", "4"):
        results["Table4"] = run_table4()
    if args.table in ("all", "5"):
        results["Table5"] = run_table5()
    if args.table in ("all", "6"):
        results["Table6"] = run_table6()
    if args.table in ("all", "e13"):
        results["E13_multires"] = run_e13()
    if args.table in ("all", "e13b"):
        results["E13b_crosssite"] = run_e13b()
    if args.table in ("all", "e13c"):
        results["E13c_windablation"] = run_e13c()
    if args.table in ("all", "e13d"):
        results["E13d_baselines"] = run_e13d()
    if args.table in ("all", "e14"):
        results["E14_conformal"] = run_e14()

    if args.table in ("all", "verify"):
        run_verification_summary()

    # Final summary
    section("FINAL STATUS")
    passed = sum(1 for v in results.values() if v)
    total  = len(results)
    for name, ok in results.items():
        print(f"  {'[PASS]' if ok else '[FAIL]'}  {name}")
    print(f"\n  {passed}/{total} tables verified against paper values.")
    if passed == total:
        print("  RESULT: All numbers in the paper are reproducible from code.")
    else:
        print("  RESULT: Some numbers need re-run. See [FAIL] items above.")

if __name__ == "__main__":
    main()
