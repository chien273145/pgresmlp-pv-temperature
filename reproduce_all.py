def run_table4():
    section("TABLE 4: Cross-Climate Transfer Matrix (expABC_fixed.py)")
    result_file = RESULTS_DIR / "expB_fixed_v2.csv"
    if not result_file.exists():
        print("  [WARN] expB_fixed_v2.csv not found.")
        return False

    import csv, math
    rows = list(csv.DictReader(result_file.read_text().splitlines()))
    t_crit = 2.093   # t(df=19, 0.975) for n=20 seeds
    n = N_SEEDS
    print(f"  CI method: x_bar +/- {t_crit} * sigma/sqrt({n})  [t-distribution, df={n-1}]")
    print()
    print(f"  {'Pair':10s}  {'Phys':>6}  {'FS3d':>6}  {'CI':>20}  {'Assessment':25s}")
    print(f"  {'-'*10}  {'-'*6}  {'-'*6}  {'-'*20}  {'-'*25}")

    # Paper Table 4 values (n=20 seeds, Bonferroni corrected)
    expected = {
        ("CO","FL"): (2.970, 0.025, 2.868, "No improvement"),
        ("CO","OR"): (1.505, 0.036, 1.568, "Significant improvement"),
        ("FL","CO"): (3.365, 0.162, 2.863, "No improvement"),
        ("FL","OR"): (1.887, 0.095, 1.568, "No improvement"),
        ("OR","CO"): (2.860, 0.055, 2.863, "Boundary"),
        ("OR","FL"): (2.560, 0.071, 2.868, "Significant improvement"),
    }

    all_ok = True
    for row in rows:
        src, tgt = row["Src"], row["Tgt"]
        phys = float(row["Phys"])
        fs   = float(row["FS3d"])
        key  = (src, tgt)
        if key in expected:
            exp_fs, exp_sd, exp_phys, exp_assess = expected[key]
            se = exp_sd / math.sqrt(n)
            ci_lo = exp_fs - t_crit * se
            ci_hi = exp_fs + t_crit * se
            if ci_hi < exp_phys:
                assess = "Significant improvement"
            elif ci_lo > exp_phys:
                assess = "No improvement"
            else:
                assess = "Boundary"
            match = assess == exp_assess
            mark = "OK" if match else "MISMATCH"
            print(f"  {src}->{tgt:3s}  {phys:>6.3f}  {fs:>6.3f}"
                  f"  [{ci_lo:.2f}, {ci_hi:.2f}]{'':<5}  {assess} [{mark}]")
            all_ok &= match
    return all_ok

