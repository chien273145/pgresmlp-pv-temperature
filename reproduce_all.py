def check(cond, msg):
    if not cond:
        print(f"  [FAIL] {msg}")
        return False
    print(f"  [OK]   {msg}")
    return True

def tol(val, target, tol_abs=0.01, label=""):
    ok = abs(val - target) <= tol_abs
    sym = "OK" if ok else "MISMATCH"
    print(f"  [{sym}] {label}: got {val:.4f}, expected {target:.4f} (tol={tol_abs})")
    return ok

